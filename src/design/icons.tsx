export type IconName = keyof typeof ICONS;

export const ICON_STROKE = 1.75;

export interface IconProps {
  name: IconName;
  size?: number;
  color?: string;
  /** Filled glyph (only for stars in ratings and the active heart). */
  fill?: string;
  style?: StyleProp<ViewStyle>;
}

export function Icon({ name, size = 20, color = '#0E0E10', fill, style }: IconProps) {
  const Cmp = ICONS[name] ?? Circle;
  return <Cmp size={size} color={color} strokeWidth={ICON_STROKE} absoluteStrokeWidth={false} fill={fill ?? 'none'} style={style} />;
}
