"""Builds the Hayve wordmark from Plus Jakarta Sans ExtraBold outlines.

The wave-v is drawn so its outer edge sits exactly on the baseline and the
x-height of the other letters. Output: src/design/logoPaths.ts (SVG paths in a
y-down coordinate space). Run: python3 scripts/build-logo.py  (needs fonttools)
"""
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

FONT = 'node_modules/@expo-google-fonts/plus-jakarta-sans/800ExtraBold/PlusJakartaSans_800ExtraBold.ttf'
TRACK = -40          # tight letter spacing (font units)
WAVE_W = 164         # wave stroke weight (heavier than the letter stems so the v reads bold)
TOP = 760            # y of the top of the viewBox (ascender of "h" is 757)
BOTTOM = -225        # descender of "y" is -220

f = TTFont(FONT)
gs = f.getGlyphSet()
cmap = f.getBestCmap()
xh = f['OS/2'].sxHeight  # 546

def glyph_path(ch, x0):
    g = gs[cmap[ord(ch)]]
    pen = SVGPathPen(gs)
    # font space (y up) -> svg space (y down, origin at TOP)
    g.draw(TransformPen(pen, (1, 0, 0, -1, x0, TOP)))
    return pen.getCommands(), g.width

paths = []
x = 0
for ch in 'hay':
    d, w = glyph_path(ch, x)
    paths.append(d)
    x += w + TRACK

# Wave-v slot: same advance as the font's "v".
v_adv = gs[cmap[ord("v")]].width + 60
h = WAVE_W / 2
def P(px, py):  # local font units -> svg coords
    return f'{x + px:.1f} {TOP - py:.1f}'
top_y = xh - h          # cap top touches x-height
bot_y = h - 6           # valley edge touches the baseline (tiny optical overshoot like round letters)
wave = (f'M {P(h + 8, top_y)} '
        f'C {P(h + 50, 290)} {P(170, bot_y)} {P(310, bot_y)} '
        f'C {P(450, bot_y)} {P(500, 380)} {P(v_adv - h - 2, top_y)}')
x_wave = x
x += v_adv + TRACK
d, w = glyph_path('e', x)
paths.append(d)
x += w

width = x
height = TOP - BOTTOM
mark_size = xh  # square viewBox for the stand-alone mark
mark = (f'M {h + 8:.1f} {mark_size - top_y:.1f} '
        f'C {h + 50:.1f} {mark_size - 290:.1f} 170 {mark_size - bot_y:.1f} 310 {mark_size - bot_y:.1f} '
        f'C 450 {mark_size - bot_y:.1f} 500 {mark_size - 380:.1f} {v_adv - h - 2:.1f} {mark_size - top_y:.1f}')

with open('src/design/logoPaths.ts', 'w') as o:
    o.write('// Generated by scripts/build-logo.py from Plus Jakarta Sans ExtraBold. Do not edit by hand.\n')
    o.write(f'export const LOGO_VIEWBOX = {{ width: {width:.0f}, height: {height} }};\n')
    o.write(f'export const LOGO_LETTERS = {paths!r};\n'.replace("'", '"'))
    o.write(f'export const LOGO_WAVE = "{wave}";\n')
    o.write(f'export const WAVE_WEIGHT = {WAVE_W};\n')
    o.write(f'/** Stand-alone wave-v in a {v_adv} x {mark_size} box (x-height tall). */\n')
    o.write(f'export const MARK_VIEWBOX = {{ width: {v_adv}, height: {mark_size} }};\n')
    o.write(f'export const MARK_WAVE = "{mark}";\n')
print('ok', width, height)
